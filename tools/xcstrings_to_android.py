"""Convert tools/ios/Localizable.xcstrings (the iOS app's string catalog) into Android strings.xml files.

Usage (from the repository root):
    python tools/xcstrings_to_android.py

Writes app/src/main/res/values{,-de,-fr,-it}/strings.xml and
tools/xcstrings_key_map.json (xcstrings key -> Android name).
The output is generated. Android-only strings live in strings_android.xml.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "ios" / "Localizable.xcstrings"
RES = ROOT / "app" / "src" / "main" / "res"
MAP_OUT = ROOT / "tools" / "xcstrings_key_map.json"
LOCALES = {"en": "values", "de": "values-de", "fr": "values-fr", "it": "values-it"}
PLACEHOLDER = re.compile(r"%(@|lld|ld|d|lf|f)")
JAVA_KEYWORDS = {
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
    "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
    "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
    "protected", "public", "return", "short", "static", "super", "switch", "synchronized", "this", "throw",
    "throws", "transient", "try", "void", "volatile", "while", "true", "false", "null",
}


def android_name(key: str) -> str:
    name = re.sub(r"[^a-z0-9]+", "_", key.lower()).strip("_")
    if name and name[0].isdigit():
        name = "n_" + name
    if name in JAVA_KEYWORDS:
        name += "_label"
    return name


def convert_value(value: str) -> str:
    # The iOS strings name the iOS app; this app is Mensa Zürich.
    value = value.replace("ETH Mensa", "Mensa Zürich")
    count = len(PLACEHOLDER.findall(value))
    index = 0

    def repl(m: re.Match) -> str:
        nonlocal index
        index += 1
        kind = "s" if m.group(1) == "@" else ("f" if "f" in m.group(1) else "d")
        return f"%{index}${kind}"

    out = PLACEHOLDER.sub(repl, value)
    if count:
        # A lone % that is not a placeholder must be doubled in formatted strings.
        out = re.sub(r"%(?!\d+\$)", "%%", out)
    out = out.replace("\\", "\\\\")
    out = out.replace("&", "&amp;").replace("<", "&lt;")
    out = out.replace("'", "\\'").replace('"', '\\"')
    out = out.replace("\n", "\\n")
    if out.startswith("@") or out.startswith("?"):
        out = "\\" + out
    return out


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    strings = data["strings"]
    names: dict[str, str] = {}
    used: set[str] = set()
    for key in strings:
        name = android_name(key)
        if not name:
            continue  # "%@" and "%@?" are pure format passthroughs.
        if name in used:
            name = f"{name}_fmt"
        used.add(name)
        names[key] = name

    for lang, folder in LOCALES.items():
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tools/xcstrings_to_android.py. Don't edit. -->",
            '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,Typos">',
        ]
        for key, name in names.items():
            loc = strings[key].get("localizations", {}).get(lang)
            if loc is None:
                continue
            if "stringUnit" in loc:
                lines.append(f'    <string name="{name}">{convert_value(loc["stringUnit"]["value"])}</string>')
            elif "variations" in loc and "plural" in loc["variations"]:
                lines.append(f'    <plurals name="{name}">')
                plural = dict(loc["variations"]["plural"])
                # French and Italian also have a "many" category (1 000 000 de …); iOS doesn't ship one.
                if lang in ("fr", "it") and "many" not in plural and "other" in plural:
                    plural["many"] = plural["other"]
                for quantity, item in plural.items():
                    text = convert_value(item["stringUnit"]["value"])
                    lines.append(f'        <item quantity="{quantity}">{text}</item>')
                lines.append("    </plurals>")
        lines.append("</resources>")
        out = RES / folder / "strings.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")

    MAP_OUT.write_text(json.dumps(names, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {MAP_OUT.relative_to(ROOT)} ({len(names)} keys)")


if __name__ == "__main__":
    main()
