"""Copies the strings the Wear OS app uses from the phone app's generated resources.

Usage (from the repository root, after xcstrings_to_android.py and android_strings.py):
    python android/tools/wear_strings.py

Writes android/wear/src/main/res/values*/strings.xml. Edit the KEYS list, not the XML.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP_RES = ROOT / "android" / "app" / "src" / "main" / "res"
WEAR_RES = ROOT / "android" / "wear" / "src" / "main" / "res"
FOLDERS = ["values", "values-de", "values-fr", "values-it"]

KEYS = [
    "app_name", "menu", "lunch", "dinner", "filter_options", "settings", "current_status", "all",
    "currently_open", "location", "all_locations", "zentrum", "honggerberg", "irchel", "sort_by",
    "sort_smart", "sort_name", "price_to_show", "student", "staff", "external",
    "no_menu_on_this_day", "no_results", "a11y_open_now", "a11y_closed",
]

STRING = re.compile(r'^\s*<string name="([^"]+)"[^>]*>.*?</string>\s*$', re.M | re.S)


def main() -> None:
    for folder in FOLDERS:
        found = {}
        for name in ("strings.xml", "strings_android.xml"):
            path = APP_RES / folder / name
            if path.exists():
                for match in STRING.finditer(path.read_text(encoding="utf-8")):
                    found.setdefault(match.group(1), match.group(0).strip())
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by android/tools/wear_strings.py from the phone app's strings. Don't edit. -->",
            "<resources>",
        ]
        for key in KEYS:
            if key in found:
                lines.append("    " + found[key])
            elif folder == "values":
                raise SystemExit(f"missing English string {key}")
        lines.append("</resources>")
        out = WEAR_RES / folder / "strings.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(KEYS)} strings in {len(FOLDERS)} locales")


if __name__ == "__main__":
    main()
