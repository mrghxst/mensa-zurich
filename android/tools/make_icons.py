"""Generates the Mensa Zürich launcher icon (phone and watch) and the in-app icon.

Usage: python android/tools/make_icons.py <lucide res/drawable dir>
The Lucide dir is the unpacked icons-lucide-android AAR (see make_shortcut_icons.py).

The icon is Lucide's utensils glyph in white on near-black, all vector. The same glyph is the
monochrome layer, so Android 13+ themed icons follow the wallpaper in light and dark mode.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODULES = [ROOT / "android" / "app" / "src" / "main" / "res", ROOT / "android" / "wear" / "src" / "main" / "res"]
BACKGROUND = "#0B0B0B"
NIGHT_TILE = "#222222"
GLYPH = 46  # dp on the 108 dp adaptive canvas (the safe zone is 66 dp)
STROKE = 1.75  # Lucide units; a little lighter than Lucide's 2 at launcher size

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icons.py from Lucide (ISC). -->\n'


def paths(lucide_dir: Path) -> list[str]:
    xml = (lucide_dir / "lucide_ic_utensils.xml").read_text(encoding="utf-8")
    return re.findall(r'android:pathData="([^"]+)"', xml)


def glyph(data: list[str], size: float, offset: float) -> str:
    scale = size / 24
    body = "".join(
        "        <path\n"
        f'            android:pathData="{d}"\n'
        '            android:strokeColor="#FFFFFF"\n'
        '            android:strokeLineCap="round"\n'
        '            android:strokeLineJoin="round"\n'
        f'            android:strokeWidth="{STROKE}" />\n'
        for d in data
    )
    return (
        f'    <group\n        android:scaleX="{scale:.4f}"\n        android:scaleY="{scale:.4f}"\n'
        f'        android:translateX="{offset:.2f}"\n        android:translateY="{offset:.2f}">\n'
        + body
        + "    </group>\n"
    )


def vector(size: int, body: str) -> str:
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}"\n    android:viewportHeight="{size}">\n'
        + body
        + "</vector>\n"
    )


ADAPTIVE = (
    HEADER
    + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
    '    <background android:drawable="@drawable/ic_launcher_background" />\n'
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
    '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
    "</adaptive-icon>\n"
)

BACKGROUND_XML = (
    HEADER
    + '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
    f'    <solid android:color="{BACKGROUND}" />\n'
    "</shape>\n"
)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    data = paths(Path(sys.argv[1]).expanduser())
    foreground = vector(108, glyph(data, GLYPH, (108 - GLYPH) / 2))
    for res in MODULES:
        write(res / "drawable" / "ic_launcher_background.xml", BACKGROUND_XML)
        write(res / "drawable" / "ic_launcher_foreground.xml", foreground)
        for name in ("ic_launcher", "ic_launcher_round"):
            write(res / "mipmap-anydpi" / f"{name}.xml", ADAPTIVE)
        print("wrote launcher icon to", res.relative_to(ROOT))

    # Square in-app icon (onboarding, About, list placeholder); the app rounds the corners.
    # In dark mode the tile is a step lighter so it doesn't vanish into the black background.
    for folder, color in (("drawable", BACKGROUND), ("drawable-night", NIGHT_TILE)):
        tile = f'    <path android:fillColor="{color}" android:pathData="M0,0h48v48h-48z" />\n'
        write(MODULES[0] / folder / "app_icon.xml", vector(48, tile + glyph(data, 28, 10)))
        print(f"wrote {folder}/app_icon.xml")


if __name__ == "__main__":
    main()
