"""Builds the launcher-shortcut and Quick Settings tile icons from Lucide vectors.

Usage: python tools/make_shortcut_icons.py <lucide res/drawable dir>
The Lucide dir is the unpacked icons-lucide-android AAR, for example
~/.gradle/caches/<gradle>/transforms/<hash>/transformed/icons-lucide-android-2.2.1/res/drawable.
Writes android/app/src/main/res/drawable/ic_shortcut_*.xml and ic_tile_legi.xml.
"""
import re
import sys
from pathlib import Path

RES = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res" / "drawable"

# shortcut id -> Lucide icon
SHORTCUTS = {
    "currently_open": "clock",
    "zentrum": "landmark",
    "hongg": "mountain",
    "irchel": "trees",
    "legi": "id_card",
}

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_shortcut_icons.py from Lucide (ISC). -->\n'


def paths(lucide_dir: Path, name: str) -> list[str]:
    xml = (lucide_dir / f"lucide_ic_{name}.xml").read_text(encoding="utf-8")
    return re.findall(r'android:pathData="([^"]+)"', xml)


def path_xml(data: str, indent: str) -> str:
    return (
        f'{indent}<path\n'
        f'{indent}    android:pathData="{data}"\n'
        f'{indent}    android:strokeColor="#FFFFFF"\n'
        f'{indent}    android:strokeLineCap="round"\n'
        f'{indent}    android:strokeLineJoin="round"\n'
        f'{indent}    android:strokeWidth="2" />\n'
    )


def foreground(data: list[str]) -> str:
    # 108 dp adaptive canvas; the 24-unit icon scaled to 40 dp inside the 66 dp safe zone.
    scale = 40 / 24
    offset = (108 - 40) / 2
    body = "".join(path_xml(d, "        ") for d in data)
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f'    <group\n        android:scaleX="{scale:.4f}"\n        android:scaleY="{scale:.4f}"\n'
        f'        android:translateX="{offset}"\n        android:translateY="{offset}">\n'
        + body
        + "    </group>\n</vector>\n"
    )


def adaptive(fg: str) -> str:
    return (
        HEADER
        + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/shortcut_background" />\n'
        f'    <foreground android:drawable="@drawable/{fg}" />\n'
        "</adaptive-icon>\n"
    )


def tile(data: list[str]) -> str:
    body = "".join(path_xml(d, "    ") for d in data)
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
        + body
        + "</vector>\n"
    )


def main() -> None:
    lucide_dir = Path(sys.argv[1]).expanduser()
    for shortcut, icon in SHORTCUTS.items():
        data = paths(lucide_dir, icon)
        (RES / f"ic_shortcut_{shortcut}_foreground.xml").write_text(foreground(data), encoding="utf-8", newline="\n")
        (RES / f"ic_shortcut_{shortcut}.xml").write_text(adaptive(f"ic_shortcut_{shortcut}_foreground"), encoding="utf-8", newline="\n")
    (RES / "ic_tile_legi.xml").write_text(tile(paths(lucide_dir, "id_card")), encoding="utf-8", newline="\n")
    # Notification small icon: the app's fork and knife.
    (RES / "ic_notification.xml").write_text(tile(paths(lucide_dir, "utensils")), encoding="utf-8", newline="\n")
    print("wrote", len(SHORTCUTS) * 2 + 2, "drawables to", RES)


if __name__ == "__main__":
    main()
